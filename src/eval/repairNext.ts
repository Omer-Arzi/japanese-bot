import * as fs from "fs";
import * as path from "path";
import { execSync } from "child_process";

const PROJECT_DIR = path.join(__dirname, "..", "..");
const IS_SMOKE = process.argv.includes("--smoke");
const FIX_TASKS_PATH = path.join(PROJECT_DIR, "evals", "runs", "latest", IS_SMOKE ? "smoke_fix_tasks.md" : "fix_tasks.md");
const NEXT_TASK_PATH = path.join(PROJECT_DIR, "evals", "runs", "latest", "next_claude_task.md");

// ─── Priority ordering ────────────────────────────────────────────────────────
// Lower index = higher priority.
const CHECK_PRIORITY: Record<string, number> = {
  // 1. Infrastructure / run errors
  "run-error":              0,
  "empty-answer":           1,
  "placeholder-text":       2,
  // 2. Lookup / routing errors
  "lookup-answer-quality":  10,
  "lookup-mode-routing":    11,
  "lookup-teaching-escape": 12,
  // 3. Factual Japanese errors
  "known-verb-error":       20,
  "particle-confusion":     21,
  "kirei-classification":   22,
  "semantic-mismatch":      23,
  "suki-particle":          24,
  "to-vs-wo":               25,
  // 4. Romaji errors
  "romaji-accuracy":        30,
  "romaji-in-example":      31,
  // 5. Style / overconfidence
  "overconfident-phrasing": 40,
  "mixed-language-garbage": 41,
  "hebrew-repetition":      42,
  "hebrew-duplicate-sentence": 43,
  "empty-parentheses":      44,
  "weird-numbering":        45,
};

function priorityOf(checkName: string): number {
  return CHECK_PRIORITY[checkName] ?? 99;
}

// ─── Task parser ──────────────────────────────────────────────────────────────

interface RawTask {
  title: string;
  checkName: string;
  body: string;
}

function parseTasksFromMd(md: string): RawTask[] {
  // Each task starts with "## Task N: Fix `check-name`"
  const sections = md.split(/^## Task \d+:/m).slice(1);
  return sections.map((section) => {
    const firstLine = section.split("\n")[0]!.trim();
    // firstLine: " Fix `romaji-accuracy`"
    const titleMatch = firstLine.match(/Fix\s+`([^`]+)`/);
    const checkName = titleMatch?.[1] ?? "unknown";
    return {
      title: `Fix \`${checkName}\``,
      checkName,
      body: ("## " + firstLine + "\n" + section.slice(firstLine.length + 1)).trim(),
    };
  });
}

function parseTotalTasks(md: string): number {
  const m = md.match(/^Total tasks:\s*(\d+)/m);
  return m ? parseInt(m[1]!, 10) : 0;
}

// ─── Runner ───────────────────────────────────────────────────────────────────

function runScript(script: string, extraArgs = ""): void {
  const cmd = extraArgs ? `npm run ${script} -- ${extraArgs}` : `npm run ${script}`;
  console.log(`\n▶  ${cmd}`);
  try {
    execSync(cmd, { cwd: PROJECT_DIR, stdio: "inherit" });
  } catch {
    console.error(`\n✗  ${script} failed (non-zero exit). Continuing anyway.`);
  }
}

// ─── Main ─────────────────────────────────────────────────────────────────────

function main(): void {
  const smokeFlag = IS_SMOKE ? "--smoke" : "";

  // 1. Run the eval pipeline
  runScript("eval:sensei", smokeFlag);
  runScript("eval:critic", smokeFlag);
  runScript("eval:fix-tasks", smokeFlag);

  // 2. Read fix_tasks.md (or smoke_fix_tasks.md).
  // If the file doesn't exist, generateFixTasks found no failures — treat as clean.
  if (!fs.existsSync(FIX_TASKS_PATH)) {
    console.log("\n✓  No failed tasks — nothing to repair!");
    if (fs.existsSync(NEXT_TASK_PATH)) fs.unlinkSync(NEXT_TASK_PATH);
    process.exit(0);
  }

  const md = fs.readFileSync(FIX_TASKS_PATH, "utf-8");
  const totalTasks = parseTotalTasks(md);

  if (totalTasks === 0) {
    console.log("\n✓  No failed tasks — nothing to repair!");
    if (fs.existsSync(NEXT_TASK_PATH)) fs.unlinkSync(NEXT_TASK_PATH);
    process.exit(0);
  }

  // 3. Extract and prioritize tasks
  const tasks = parseTasksFromMd(md);
  tasks.sort((a, b) => priorityOf(a.checkName) - priorityOf(b.checkName));
  const top = tasks[0]!;

  // 4. Write next_claude_task.md
  const suiteLabel = IS_SMOKE ? "smoke" : "full";
  const header = [
    "# Next Repair Task",
    "",
    `> Generated by \`npm run eval:repair:next${IS_SMOKE ? " -- --smoke" : ""}\` (${suiteLabel} suite)`,
    `> Total open tasks: ${totalTasks}`,
    `> This is the highest-priority task. Fix it, then re-run \`npm run eval:repair:next\`.`,
    "",
    "---",
    "",
  ].join("\n");

  fs.writeFileSync(NEXT_TASK_PATH, header + top.body + "\n", "utf-8");

  // 5. Print summary
  console.log("\n" + "─".repeat(60));
  console.log(`  Open tasks  : ${totalTasks}`);
  console.log(`  Next task   : ${top.title}`);
  console.log(`  Written to  : ${path.relative(PROJECT_DIR, NEXT_TASK_PATH)}`);
  console.log("─".repeat(60));
  console.log("\n  Paste this file into Claude Code:\n");
  console.log(`    cat ${path.relative(PROJECT_DIR, NEXT_TASK_PATH)}\n`);
}

main();